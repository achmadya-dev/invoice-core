import { readFile } from 'node:fs/promises'
import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('creates, applies, edits, and deletes a recurring template without changing an existing invoice', async ({
  page,
}, info) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Manage templates' }).click()
  await expect(page).toHaveURL(/#templates$/)
  await page.getByRole('button', { name: 'New template' }).click()
  const form = page.getByRole('form', { name: 'New template' })
  await expect(form.getByLabel('Template name')).toBeFocused()
  await form.getByLabel('Template name').fill('Monthly maintenance')
  await form.getByLabel('Description, item 1').fill('Monitoring')
  await form.getByLabel('Quantity, item 1').fill('2.5')
  await form.getByLabel('Rate, item 1').fill('-5')
  await form.getByRole('button', { name: 'Save template' }).click()
  await expect(form.getByRole('alert')).toHaveText('Correct the highlighted quantities or rates.')
  await expect(form.getByLabel('Rate, item 1')).toHaveAttribute('aria-invalid', 'true')
  await form.getByLabel('Rate, item 1').fill('100')
  await form.getByRole('button', { name: 'Add line item' }).click()
  await expect(form.getByLabel('Description, item 2')).toBeFocused()
  await form.getByLabel('Description, item 2').fill('Service credit')
  await form.getByLabel('Quantity, item 2').fill('-1')
  await form.getByLabel('Rate, item 2').fill('25')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: info.outputPath('template-form-desktop.png'), fullPage: true })
  await form.getByRole('button', { name: 'Save template' }).click()
  await expect(page.getByRole('status')).toHaveText('Template saved.')
  await page.reload()

  const nav = page.getByRole('navigation', { name: 'Workspace' })
  await expect(nav.getByRole('button', { name: 'Templates' })).toHaveAttribute(
    'aria-current',
    'page',
  )
  await expect(page.getByRole('button', { name: 'Monthly maintenance USD' })).toBeVisible()
  await nav.getByRole('button', { name: 'Editor' }).click()
  await page.getByLabel('Client name', { exact: true }).fill('Example customer')
  await page.getByLabel('Description, item 1').fill('Existing draft line')
  const currency = page.getByRole('combobox', { name: 'Currency', exact: true })
  await currency.click()
  await page.getByRole('option', { name: /^EUR —/ }).click()
  const picker = page.getByRole('combobox', { name: 'Line item template' })
  await picker.click()
  await expect(page.getByRole('group', { name: 'My templates' })).toBeVisible()
  await page.getByRole('option', { name: 'Monthly maintenance (USD)', exact: true }).click()
  const apply = page.getByRole('button', { name: 'Apply', exact: true })
  await apply.click()
  await expect(page.getByRole('alert')).toContainText('This template uses USD')
  await expect(page.getByLabel('Description, item 1')).toHaveValue('Existing draft line')
  await currency.click()
  await page.getByRole('option', { name: /^USD —/ }).click()
  await apply.click()
  const dialog = page.getByRole('alertdialog')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByLabel('Description, item 1')).toHaveValue('Existing draft line')
  await apply.click()
  await dialog.getByRole('button', { name: 'Replace line items' }).click()
  await expect(page.getByLabel('Description, item 1')).toHaveValue('Monitoring')
  await expect(page.getByLabel('Quantity, item 1')).toHaveValue('2.5')
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('100')
  await expect(page.getByLabel('Description, item 2')).toHaveValue('Service credit')
  await expect(page.getByLabel('Quantity, item 2')).toHaveValue('-1')
  await expect(page.getByLabel('Rate, item 2')).toHaveValue('25')
  await page.getByRole('button', { name: 'Save invoice' }).click()
  await expect(page.getByRole('status')).toHaveText('Invoice saved to history.')

  await nav.getByRole('button', { name: 'Templates' }).click()
  const saved = page.getByRole('button', { name: 'Monthly maintenance USD' })
  await saved.click()
  await page.getByLabel('Rate, item 1').fill('120')
  await page.getByRole('button', { name: 'Save template' }).click()
  await saved.click()
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('120')
  await page.getByRole('button', { name: 'Delete template' }).click()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(saved).toBeVisible()
  await page.getByRole('button', { name: 'Delete template' }).click()
  await dialog.getByRole('button', { name: 'Delete template' }).click()
  await expect(saved).toHaveCount(0)
  await nav.getByRole('button', { name: 'Editor' }).click()
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('100')
  await nav.getByRole('button', { name: 'History' }).click()
  await expect(page.getByText('$225.00', { exact: true })).toBeVisible()
})

test('fits the mobile workspace and includes templates in backup, clear, and restore', async ({
  page,
}, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#templates')
  await page.getByRole('button', { name: 'New template' }).press('Enter')
  await expect(page.getByLabel('Template name')).toBeFocused()
  await page.getByLabel('Template name').fill('Weekly support')
  await page.getByLabel('Description, item 1').fill('Support session')
  await page.getByLabel('Rate, item 1').fill('85')
  await page.screenshot({ path: info.outputPath('template-form-mobile.png'), fullPage: true })

  await page.setViewportSize({ width: 320, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.getByRole('button', { name: 'Save template' }).click()
  const nav = page.getByRole('navigation', { name: 'Workspace' })
  await nav.getByRole('button', { name: 'Backup' }).click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download backup' }).click()
  const buffer = await readFile(await (await downloadEvent).path())
  const dialog = page.getByRole('alertdialog')
  await page.getByRole('button', { name: 'Clear local workspace' }).click()
  await expect(dialog).toContainText('1 custom template(s)')
  await dialog.getByRole('button', { name: 'Confirm clear workspace' }).click()
  await nav.getByRole('button', { name: 'Templates' }).click()
  await expect(page.getByText('No custom templates yet.')).toBeVisible()
  await nav.getByRole('button', { name: 'Backup' }).click()
  await page.getByLabel('Invoice Core backup file').setInputFiles({
    name: 'workspace.json',
    mimeType: 'application/json',
    buffer,
  })
  await expect(dialog).toContainText('1 custom template(s)')
  await dialog.getByRole('button', { name: 'Replace local workspace' }).click()
  await nav.getByRole('button', { name: 'Templates' }).click()
  await page.getByRole('button', { name: 'Weekly support USD' }).click()
  await expect(page.getByLabel('Description, item 1')).toHaveValue('Support session')
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('85')
})
