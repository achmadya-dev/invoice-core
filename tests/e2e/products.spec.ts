test('uses the separate product picker to add every item in a group', async ({ page }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Catalog', exact: true }).click()
  await page.getByRole('button', { name: 'Add product', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New product' })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('Product name').fill('Maintenance plan')
  await dialog.getByLabel('Description, item 1').fill('Monitoring')
  await dialog.getByLabel('Quantity, item 1').fill('2.5')
  await dialog.getByLabel('Rate, item 1').fill('-5')
  await dialog.getByRole('button', { name: 'Save product' }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Correct the highlighted quantities or rates.')
  await dialog.getByLabel('Rate, item 1').fill('100')
  await dialog.getByRole('button', { name: 'Add line item' }).click()
  await dialog.getByLabel('Description, item 2').fill('Priority response')
  await dialog.getByLabel('Rate, item 2').fill('25')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: info.outputPath('product-modal-desktop.png') })
  await dialog.getByRole('button', { name: 'Save product' }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Maintenance plan' })).toBeVisible()
  const nav = page.getByRole('navigation', { name: 'Workspace' })
  await nav.getByRole('button', { name: 'Invoices' }).click()
  await page.getByRole('button', { name: 'Create invoice', exact: true }).click()
  const details = page.getByRole('region', { name: 'Invoice options' })
  const lines = page.getByRole('region', { name: 'Line items' })
  await expect(details.getByRole('combobox', { name: 'Company', exact: true })).toBeVisible()
  const picker = details.getByRole('combobox', { name: 'Add product', exact: true })
  const currency = page.getByRole('combobox', { name: 'Currency', exact: true })
  await currency.click()
  await page.getByRole('option', { name: /^EUR —/ }).click()
  await picker.fill('main')
  await page.getByRole('option', { name: /^Maintenance plan/ }).click()
  await expect(details.getByRole('alert')).toContainText('This product uses USD')
  await expect(page.getByLabel('Description, item 1')).toHaveValue('')
  await currency.click()
  await page.getByRole('option', { name: /^USD —/ }).click()
  await picker.fill('main')
  await page.getByRole('option', { name: /^Maintenance plan/ }).click()
  await expect(page.getByLabel('Description, item 1')).toHaveValue('Monitoring')
  await expect(page.getByLabel('Quantity, item 1')).toHaveValue('2.5')
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('100')
  await expect(page.getByLabel('Description, item 2')).toHaveValue('Priority response')
  await expect(page.getByLabel('Rate, item 2')).toHaveValue('25')
  await expect(lines.getByRole('cell', { name: '$250.00', exact: true })).toBeVisible()
  await picker.fill('main')
  await picker.press('ArrowDown')
  await picker.press('Enter')
  await expect(page.getByLabel('Description, item 3')).toHaveValue('Monitoring')
  await expect(page.getByLabel('Description, item 4')).toHaveValue('Priority response')
  await page.getByLabel('Rate, item 3').fill('200')
  await page.getByLabel('Sender name').fill('Synthetic sender')
  const client = page.getByRole('textbox', { name: 'Client', exact: true })
  await client.fill('Synthetic client')
  await page.getByLabel('Issue date').fill('2026-11-24')
  await page.getByRole('button', { name: 'Create invoice', exact: true }).click()
  await expect(page.getByRole('button', { name: 'INV-0001', exact: true })).toBeVisible()

  await nav.getByRole('button', { name: 'Catalog' }).click()
  await page.getByRole('button', { name: 'Edit Maintenance plan' }).click()
  const editDialog = page.getByRole('dialog', { name: 'Edit product' })
  await expect(editDialog.getByLabel('Rate, item 1')).toHaveValue('100')
  await editDialog.getByLabel('Rate, item 1').fill('120')
  await editDialog.getByRole('button', { name: 'Save product' }).click()
  await expect(page.getByText('2 items · USD')).toBeVisible()
  await page.getByRole('button', { name: 'Delete Maintenance plan' }).click()
  const confirm = page.getByRole('alertdialog')
  await confirm.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Maintenance plan' })).toBeVisible()
  await page.getByRole('button', { name: 'Delete Maintenance plan' }).click()
  await confirm.getByRole('button', { name: 'Delete product' }).click()
  await expect(page.getByRole('heading', { name: 'Maintenance plan' })).toHaveCount(0)
  await nav.getByRole('button', { name: 'Invoices' }).click()
  await page.getByRole('button', { name: 'INV-0001', exact: true }).click()
  await expect(page.getByLabel('Rate, item 1')).toHaveValue('100')
  await expect(page.getByLabel('Rate, item 2')).toHaveValue('25')
  await expect(page.getByLabel('Rate, item 3')).toHaveValue('200')
})

test('copies saved clients separately and edits client text directly on the sheet', async ({
  page,
}) => {
  await page.goto('/')
  const create = page.getByRole('button', { name: 'Create invoice', exact: true })
  const client = page.getByRole('textbox', { name: 'Client', exact: true })
  const picker = page.getByRole('combobox', { name: 'Use saved client', exact: true })
  await create.click()
  await page.getByLabel('Sender name').fill('Northline Studio')
  await client.fill('Fieldwork Press')
  await page.getByLabel('Description, item 1').fill('Design')
  await page.getByLabel('Billing contact email').fill('billing@example.com')
  await create.click()
  await create.click()
  await picker.fill('field')
  await page.getByRole('option', { name: 'Fieldwork Press billing@example.com' }).click()
  await expect(client).toHaveValue('Fieldwork Press')
  await expect(page.getByLabel('Billing contact email')).toHaveValue('billing@example.com')
  await client.fill('Fieldwork Press LLC')
  await expect(page.getByLabel('Billing contact email')).toHaveValue('billing@example.com')
  await page.getByLabel('Billing contact email').fill('')
  await page.getByLabel('Invoice number').click()
  await expect(client).toHaveValue('Fieldwork Press LLC')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(
    page.getByRole('article', { name: 'Invoice document' }).getByText('Fieldwork Press LLC'),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await picker.fill('Discarded query')
  await picker.press('Escape')
  await expect(client).toHaveValue('Fieldwork Press LLC')
})

test('fits mobile and includes products in the backup dialog workflows', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#products')
  await page.getByRole('button', { name: 'Add product', exact: true }).press('Enter')
  const productDialog = page.getByRole('dialog', { name: 'New product' })
  await productDialog.getByLabel('Product name').fill('Weekly support')
  await productDialog.getByLabel('Description, item 1').fill('Support session')
  await productDialog.getByLabel('Rate, item 1').fill('85')
  await page.screenshot({ path: info.outputPath('product-modal-mobile.png') })
  await page.setViewportSize({ width: 320, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await productDialog.getByRole('button', { name: 'Save product' }).click()
  const nav = page.getByRole('navigation', { name: 'Workspace' })
  await nav.getByRole('button', { name: 'Invoices' }).click()
  const backup = page.getByRole('button', { name: 'Backup', exact: true })
  await backup.click()
  const backupDialog = page.getByRole('dialog', { name: 'Backup' })
  await expect(backupDialog).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await backupDialog.getByRole('button', { name: 'Download backup' }).click()
  const buffer = await readFile(await (await downloadEvent).path())
  const confirm = page.getByRole('alertdialog')
  await backupDialog.getByRole('button', { name: 'Clear local workspace' }).click()
  await expect(confirm).toContainText('1 product(s)')
  await confirm.getByRole('button', { name: 'Confirm clear workspace' }).click()
  await nav.getByRole('button', { name: 'Catalog' }).click()
  await expect(page.getByText('No products yet.', { exact: false })).toBeVisible()
  await nav.getByRole('button', { name: 'Invoices' }).click()
  await backup.click()
  await backupDialog.getByLabel('Invoice Core backup file').setInputFiles({
    name: 'workspace.json',
    mimeType: 'application/json',
    buffer,
  })
  await expect(confirm).toContainText('1 product(s)')
  await confirm.getByRole('button', { name: 'Replace local workspace' }).click()
  await nav.getByRole('button', { name: 'Catalog' }).click()
  await page.getByRole('button', { name: 'Edit Weekly support' }).click()
  const restored = page.getByRole('dialog', { name: 'Edit product' })
  await expect(restored.getByLabel('Description, item 1')).toHaveValue('Support session')
  await expect(restored.getByLabel('Rate, item 1')).toHaveValue('85')
})
