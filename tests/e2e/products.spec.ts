test('copies saved clients separately and edits client text directly on the sheet', async ({
  page,
}) => {
  await page.goto('/')
  const create = page.getByRole('button', { name: 'Create invoice', exact: true })
  const client = page.getByRole('textbox', { name: 'Client', exact: true })
  await create.click()
  await page.getByLabel('Sender name').fill('Northline Studio')
  await client.fill('Fieldwork Press')
  await page.getByLabel('Description, item 1').fill('Design')
  await page.getByLabel('Billing contact email').fill('billing@example.com')
  await create.click()
  await create.click()
  const sheet = page.getByRole('article', { name: 'Editable invoice' })
  const openClientModal = sheet.getByRole('button', { name: 'Use saved client', exact: true })
  const clientModal = page.getByRole('dialog', { name: 'Use saved client' })
  await openClientModal.click()
  await expect(clientModal).toBeVisible()
  await clientModal.getByLabel('Search saved clients').fill('field')
  await clientModal.getByRole('button', { name: /Fieldwork Press billing@example\.com/ }).click()
  await expect(clientModal).toHaveCount(0)
  await expect(client).toHaveValue('Fieldwork Press')
  await expect(page.getByLabel('Billing contact email')).toHaveValue('billing@example.com')
  await client.fill('Fieldwork Press LLC')
  await expect(page.getByLabel('Billing contact email')).toHaveValue('billing@example.com')
  await page.getByLabel('Billing contact email').fill('')
  await page.getByLabel('Invoice number').click()
  await expect(client).toHaveValue('Fieldwork Press LLC')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(
    page.getByRole('article', { name: 'Invoice document' }).getByText('Fieldwork Press LLC'),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await openClientModal.click()
  await clientModal.getByLabel('Search saved clients').fill('Discarded query')
  await page.keyboard.press('Escape')
  await expect(clientModal).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: 'New invoice' })).toBeVisible()
  await expect(client).toHaveValue('Fieldwork Press LLC')
})

test('fits mobile and includes products in the backup dialog workflows', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#products')
  await page.getByRole('button', { name: 'Add product', exact: true }).press('Enter')
  const productDialog = page.getByRole('dialog', { name: 'New product' })
  await productDialog.getByLabel('Product name').fill('Weekly support')
  await productDialog.getByLabel('Description, item 1').fill('Support session')
  await productDialog.getByLabel('Rate, item 1').fill('85')
  await page.screenshot({ path: info.outputPath('product-modal-mobile.png') })
  await page.setViewportSize({ width: 320, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await productDialog.getByRole('button', { name: 'Save product' }).click()
  const tabs = page.getByRole('tablist', { name: 'Workspace sections' })
  await tabs.getByRole('tab', { name: 'Invoices', exact: true }).click()
  const backup = page.getByRole('button', { name: 'Backup', exact: true })
  await backup.click()
  const backupDialog = page.getByRole('dialog', { name: 'Backup' })
  await expect(backupDialog).toBeVisible()
  const downloadEvent = page.waitForEvent('download')
  await backupDialog.getByRole('button', { name: 'Download backup' }).click()
  const buffer = await readFile(await (await downloadEvent).path())
  const confirm = page.getByRole('alertdialog')
  await backupDialog.getByRole('button', { name: 'Clear local workspace' }).click()
  await expect(confirm).toContainText('1 product(s)')
  await confirm.getByRole('button', { name: 'Confirm clear workspace' }).click()
  await tabs.getByRole('tab', { name: 'Products', exact: true }).click()
  await expect(page.getByText('No products yet.', { exact: false })).toBeVisible()
  await tabs.getByRole('tab', { name: 'Invoices', exact: true }).click()
  await backup.click()
  await backupDialog.getByLabel('Invoice Core backup file').setInputFiles({
    name: 'workspace.json',
    mimeType: 'application/json',
    buffer,
  })
  await expect(confirm).toContainText('1 product(s)')
  await confirm.getByRole('button', { name: 'Replace local workspace' }).click()
  await tabs.getByRole('tab', { name: 'Products', exact: true }).click()
  await page.getByRole('button', { name: 'Edit Weekly support' }).click()
  const restored = page.getByRole('dialog', { name: 'Edit product' })
  await expect(restored.getByLabel('Description, item 1')).toHaveValue('Support session')
  await expect(restored.getByLabel('Rate, item 1')).toHaveValue('85')
})

test('highlights unfilled required fields in red inside catalog modals', async ({ page }, info) => {
  const errorBorder = 'rgb(139, 35, 54)'
  const errorBg = 'rgb(255, 242, 244)'

  await page.goto('/')
  const tabs = page.getByRole('tablist', { name: 'Workspace sections' })
  await tabs.getByRole('tab', { name: 'Products', exact: true }).click()

  // 1. New product modal
  await page.getByRole('button', { name: 'Add product', exact: true }).click()
  const productDialog = page.getByRole('dialog', { name: 'New product' })
  const productName = productDialog.getByLabel('Product name')
  const itemDescription = productDialog.getByLabel('Description, item 1')
  await expect(productName).not.toHaveAttribute('aria-invalid', 'true')
  await expect(itemDescription).not.toHaveAttribute('aria-invalid', 'true')

  await productDialog.getByRole('button', { name: 'Save product' }).click()
  await expect(productDialog.getByRole('alert')).toHaveText('Enter a product name.')
  await expect(productName).toHaveAttribute('aria-invalid', 'true')
  await expect(productName).toHaveCSS('border-color', errorBorder)
  await expect(productName).toHaveCSS('background-color', errorBg)
  await expect(itemDescription).toHaveAttribute('aria-invalid', 'true')
  await expect(itemDescription).toHaveCSS('border-color', errorBorder)
  await expect(itemDescription).toHaveCSS('background-color', errorBg)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await productDialog.screenshot({ path: info.outputPath('product-modal-invalid.png') })

  await productName.fill('Maintenance plan')
  await expect(productName).not.toHaveAttribute('aria-invalid', 'true')
  await expect(itemDescription).toHaveAttribute('aria-invalid', 'true')
  await itemDescription.fill('Monthly checkup')
  await expect(itemDescription).not.toHaveAttribute('aria-invalid', 'true')

  await productDialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add product', exact: true }).click()
  await expect(productDialog.getByLabel('Product name')).not.toHaveAttribute('aria-invalid', 'true')
  await expect(productDialog.getByLabel('Description, item 1')).not.toHaveAttribute(
    'aria-invalid',
    'true',
  )
  await productDialog.getByRole('button', { name: 'Cancel', exact: true }).click()

  // 2. New company modal
  await page.getByRole('tab', { name: 'Companies', exact: true }).click()
  await page.getByRole('button', { name: 'Add company', exact: true }).click()
  const companyDialog = page.getByRole('dialog', { name: 'New company' })
  const senderName = companyDialog.getByLabel('Sender name')
  const nextNumber = companyDialog.getByLabel('Next number')
  const padding = companyDialog.getByLabel('Number padding')
  await expect(senderName).not.toHaveAttribute('aria-invalid', 'true')
  await expect(nextNumber).not.toHaveAttribute('aria-invalid', 'true')
  await expect(padding).not.toHaveAttribute('aria-invalid', 'true')

  await nextNumber.fill('')
  await padding.fill('')
  await companyDialog.getByRole('button', { name: 'Save company' }).click()
  await expect(companyDialog.getByRole('alert')).toHaveText('Enter a company name.')
  for (const field of [senderName, nextNumber, padding]) {
    await expect(field).toHaveAttribute('aria-invalid', 'true')
    await expect(field).toHaveCSS('border-color', errorBorder)
    await expect(field).toHaveCSS('background-color', errorBg)
  }
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await companyDialog.screenshot({ path: info.outputPath('company-modal-invalid.png') })

  await senderName.fill('North Studio')
  await nextNumber.fill('1')
  await padding.fill('4')
  for (const field of [senderName, nextNumber, padding]) {
    await expect(field).not.toHaveAttribute('aria-invalid', 'true')
  }

  await companyDialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add company', exact: true }).click()
  await expect(companyDialog.getByLabel('Sender name')).not.toHaveAttribute('aria-invalid', 'true')
  await expect(companyDialog.getByLabel('Next number')).not.toHaveAttribute('aria-invalid', 'true')
  await expect(companyDialog.getByLabel('Number padding')).not.toHaveAttribute(
    'aria-invalid',
    'true',
  )
})
